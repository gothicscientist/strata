"use client";

import Link from "next/link";
import { api } from "@/lib/api";
import { analysisLabel } from "@/lib/format";
import { useResource } from "@/lib/useResource";
import { Caveat, Empty, ErrorNote, KindMark, Loading, PageHeader } from "@/components/typography";

export default function ExamplesPage() {
  const ex = useResource((s) => api.examples(s), []);
  return (
    <>
      <PageHeader
        kicker="Worked examples"
        title="Example analyses"
        lede="Real analyses on public data."
      />
      {ex.loading ? (
        <Loading what="examples" />
      ) : ex.error ? (
        <ErrorNote error={ex.error} retry={ex.reload} />
      ) : !ex.data?.length ? (
        <Empty>
          No precomputed examples are published on this server yet. They are generated by the data
          pipeline (<code>data/pipeline</code>) once the reference library has been built; see{" "}
          <Link href="/data/">Data</Link>.
        </Empty>
      ) : (
        <>
        {[...new Set(ex.data.map((e) => e.caveats?.[0]).filter((c): c is string => !!c))].map((c) => (
          <Caveat key={c} title="About these examples">
            {c}
          </Caveat>
        ))}
        <ul className="panel max-w-[56rem] divide-y divide-rule-soft">
          {ex.data.map((e) => (
            <li key={e.slug}>
              <Link
                href={`/examples/view/?slug=${encodeURIComponent(e.slug)}`}
                className="group block px-5 py-5 no-underline hover:bg-wash sm:px-6"
              >
                <span className="flex flex-wrap items-center gap-2 text-caption text-ink-3">
                  <KindMark kind={e.result_kind} />
                  {analysisLabel(e.kind)}
                  {e.tags?.length ? <span>{e.tags.join(", ")}</span> : null}
                </span>
                <h2 className="mt-1.5 text-[1.35rem] leading-snug font-semibold text-ink group-hover:text-malachite">
                  {e.title}
                </h2>
              </Link>
            </li>
          ))}
        </ul>
        </>
      )}
    </>
  );
}
